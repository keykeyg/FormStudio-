    def request(self, path, obj=None, token=app.TOKEN):
        req = urllib.request.Request(self.base+path, data=None if obj is None else json.dumps(obj).encode(), headers={'Content-Type':'application/json','X-Form-Token':token})
        with urllib.request.urlopen(req, timeout=10) as r:
            return json.load(r)

    def wait(self, pid, payload):
        jid = self.request('/api/projects/'+pid+'/jobs', payload)['job']
        deadline=time.time()+120
        while time.time()<deadline:
            result=self.request('/api/jobs/'+jid)
            if result['status'] != 'running':
                return result
            time.sleep(.1)
        self.fail('Job timed out')


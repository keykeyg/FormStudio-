class MockLM(BaseHTTPRequestHandler):
    replies = []
    requests = []
    loaded = True
    vision = True
    delay = 0.0

    def log_message(self, *args):
        pass

    def do_GET(self):
        body = json.dumps({"models": [{"key": "test-vision", "type": "llm", "display_name": "Test vision", "capabilities": {"vision": self.vision}, "loaded_instances": [{"id": "test-vision"}] if self.loaded else []}]}).encode()
        self.send_response(200)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_POST(self):
        request = json.loads(self.rfile.read(int(self.headers['Content-Length'])))
        self.requests.append(request)
        if self.delay:
            time.sleep(self.delay)  # simulates a long prompt-processing phase (no bytes sent yet)
        response = self.replies.pop(0) if self.replies else ''
        body = ("data: " + json.dumps({"choices": [{"delta": {"content": response}}]}) + "\n\ndata: [DONE]\n\n").encode()
        self.send_response(200)
        self.send_header('Content-Type', 'text/event-stream')
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        self.wfile.write(body)



    def test_phone_access_requires_passcode(self):
        # Settings: passcode required before turning it on; the hash is never sent back.
        with self.assertRaises(urllib.error.HTTPError):
            self.request('/api/config',{'remote_access':True})
        cfg=self.request('/api/config',{'remote_access':True,'remote_passcode':'grip-1234'})
        self.assertTrue(cfg['remote_passcode_set']); self.assertNotIn('remote_passcode_hash',cfg); self.assertNotIn('remote_passcode_salt',cfg)

        class Remote(app.Handler):
            def client_is_local(self):
                return False
        server=ThreadingHTTPServer(('127.0.0.1',0),Remote)
        threading.Thread(target=server.serve_forever,daemon=True).start()
        base='http://127.0.0.1:%d' % server.server_port
        opener=urllib.request.build_opener(urllib.request.HTTPCookieProcessor(), urllib.request.ProxyHandler({}))
        class NoRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, *a, **k):
                return None
        plain=urllib.request.build_opener(NoRedirect, urllib.request.ProxyHandler({}))
        app.REMOTE=True
        try:
            with self.assertRaises(urllib.error.HTTPError) as c:
                plain.open(base+'/',timeout=10)
            self.assertEqual(c.exception.code,302); self.assertEqual(c.exception.headers['Location'],'/login')
            with self.assertRaises(urllib.error.HTTPError) as c:
                plain.open(base+'/api/session',timeout=10)
            self.assertEqual(c.exception.code,401)
            with plain.open(base+'/login',timeout=10) as r:
                self.assertIn(b'passcode',r.read())
            def login(code):
                return opener.open(urllib.request.Request(base+'/api/login',data=json.dumps({'passcode':code}).encode(),headers={'Content-Type':'application/json'}),timeout=10)
            with self.assertRaises(urllib.error.HTTPError) as c:
                login('wrong-one')
            self.assertEqual(c.exception.code,401)
            with login('grip-1234') as r:
                self.assertIn('HttpOnly',r.headers['Set-Cookie'])
            with opener.open(base+'/api/session',timeout=10) as r:
                session=json.load(r)
            self.assertFalse(session['local'])
            with opener.open(base+'/api/projects',timeout=10) as r:
                self.assertIsInstance(json.load(r),list)
            # A logged-in phone still can't change settings.
            req=urllib.request.Request(base+'/api/config',data=b'{"cad_python":"x"}',headers={'Content-Type':'application/json','X-Form-Token':session['token']})
            with self.assertRaises(urllib.error.HTTPError) as c:
                opener.open(req,timeout=10)
            self.assertEqual(c.exception.code,403)
            # Rate limit: 5 wrong tries, then 429 even for the right code.
            app.LOGIN_FAILS.clear()
            for _ in range(5):
                with self.assertRaises(urllib.error.HTTPError):
                    login('nope-nope')
            with self.assertRaises(urllib.error.HTTPError) as c:
                login('grip-1234')
            self.assertEqual(c.exception.code,429)
        finally:
            app.REMOTE=False; app.LOGIN_FAILS.clear()
            server.shutdown(); server.server_close()
            saved=json.loads((app.DATA/'settings.json').read_text())
            for k in ('remote_access','remote_passcode_salt','remote_passcode_hash'):
                saved.pop(k,None)
            app.atomic(app.DATA/'settings.json',saved)

